# Шанс найти ключ по номеру обыска (план 59.2: первый — никогда, дальше
# 25/40/60%, на 5-м гарантированно).
KEY_CHANCES = {1: 0.0, 2: 0.25, 3: 0.40, 4: 0.60}
KEY_GUARANTEED_AT = 5
STAGE_KEY_HUNT = 2


def key_chance(attempt: int) -> float:
    if attempt >= KEY_GUARANTEED_AT:
        return 1.0
    return KEY_CHANCES.get(attempt, 0.0)


def roll_key(run: Run, rng: Callable[[], float]) -> bool:
    """Новый обыск нового места на стадии поиска ключа: считаем попытку и
    бросаем кубик. True — ключ здесь. Решает код, Ведущий лишь обставляет."""
    attempt = int(run.world.get("key_searches") or 0) + 1
    run.world["key_searches"] = attempt
    found = rng() < key_chance(attempt)
    if found:
        run.world["key_found"] = True
    return found


def stage_gate(run: Run, target: int) -> int:
    """Условия сюжета поверх решения Ведущего: в стадию 3 — только с ключом,
    и с ключом со стадии 2 — всегда."""
    found = bool(run.world.get("key_found"))
    if run.stage == STAGE_KEY_HUNT and found:
        return STAGE_KEY_HUNT + 1
    if target > STAGE_KEY_HUNT and not found:
        return STAGE_KEY_HUNT
    return target


def search_outcome_text(where: str, kind: str, text: str, *, key: bool, hunting: bool) -> str:
    """Исход обыска для Ведущего (блок extra_input) — слова, не механика."""
    if key:
        return (
            f"Альфред обыскал «{where}» и НАХОДИТ ключ от замка подвала. Опиши, "
            "как он выглядит и как Альфред на него натыкается."
        )
    if hunting:
        tail = "Ключа здесь нет — ни в каком виде; опиши, чем это место пусто или что в нём есть."
        if kind == places.SEARCH_KIND_TRINKET:
            return f"Альфред обыскал «{where}». {text} {tail}"
        if kind == places.SEARCH_KIND_REPEAT:
            return f"Альфред снова обшаривает «{where}». Там уже всё обыскано, ничего нового."
        return f"Альфред обыскал «{where}». {tail}"
    return f"Альфред обыскал «{where}». {text}"


def extra_input(run: Run) -> str:
    """Блок ко входу Ведущего: где Альфред, где уже побывали, исход обыска."""
    lines = []
    here = run.world.get("here")
    if here:
        lines.append(f"Альфред сейчас: {here}.")
    visited = [
        str(r.get("name"))
        for r in (run.world.get("rooms") or {}).values()
        if isinstance(r, dict) and r.get("name")
    ]
    if run.stage == STAGE_KEY_HUNT and visited:
        lines.append("Для ключа уже обошли: " + ", ".join(visited) + ".")
    outcome = run.world.get("search_outcome")
    if outcome:
        lines.append("Исход обыска (определён кодом, НЕ меняй): " + str(outcome))
    return "\n".join(lines) or "Альфред пока ничего не искал."


