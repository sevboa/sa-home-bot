_DIRECTIVE_MARKER = (
    "[СИСТЕМНАЯ ДИРЕКТИВА, не слова собеседника: он тебе только что ничего "
    "не говорил, это инструкция от инфраструктуры Альфреда, не от человека. "
    "Не открывай ответ подтверждением ЧУЖОГО распоряжения («Принято», "
    "«исполню ваше поручение» и т.п.) — как будто это сказал собеседник. "
    "Действуй по указанному ниже: либо от своего имени, по инициативе, "
    "либо как курьер, передающий весть от третьего лица своими словами.]\n"
)


def wrap_context_note(body: str) -> dict[str, str]:
    return {"role": "system", "content": body}


def wrap_system_directive(body: str) -> dict[str, str]:
    return {"role": _DIRECTIVE_ROLE, "content": _DIRECTIVE_MARKER + body}
