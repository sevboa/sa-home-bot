THINK_MARKER = "[[NEEDS_THINKING]]"
ROUTE_OK = "OK"

_ROUTER_LEVEL_RE = re.compile(r"THINK\s*:?\s*([0-3])", re.IGNORECASE)


def parse_router_level(text: str) -> int:
    m = _ROUTER_LEVEL_RE.search(text or "")
    if m:
        return int(m.group(1))
    if THINK_MARKER in (text or ""):
        return 3
    return 0


