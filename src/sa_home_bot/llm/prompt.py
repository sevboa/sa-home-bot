# Живая находка 2026-07-25: раньше решение "думать ли/звать ли тул" и вывод
# уже в характере смешивались в ОДНОМ вызове ("быстрый проход" — SYSTEM_PROMPT
# персонажа + отдельным system-сообщением инструкция-триаж поверх него, см.
# git-историю bot/ai_flow.py::_TRIAGE_INSTRUCTION). На практике модель на
# фоне 12 конкурирующих правил персонажа (тон, анти-повтор, конфликты,
# внешность и т.д.) регулярно проваливала именно триаж — отвечала на
# головоломку про кружку с ходу, не запросив think, хотя нужный текст
# (в persona_prompt, см. докстринг модуля) физически был в контексте.
# Решение пользователя 2026-07-25: вынести триаж в ОТДЕЛЬНЫЙ вызов без
# единого слова о персонаже — ``ROUTER_SYSTEM_PROMPT`` — и только по его
# решению делать второй, персонажный вызов с уже известным think. Дороже
# (гарантированный второй вызов на КАЖДОЕ сообщение, не только на сложные),
# но роутер не конкурирует за внимание модели ни с чем, кроме самой задачи
# классификации.
#
# Уточнение 2026-08-10: вызов по-прежнему отдельный, но этот текст больше не
# занимает system[0] — он идёт ПОСЛЕДНИМ системным сообщением, а system[0] у
# обоих проходов один и тот же (персонаж). Так у них общий префикс, и KV-кэш
# роутерного прохода достаётся персонажному даром (llm/service.py, ветка
# ACTION_CHAT). Конкуренции за внимание это не возвращает: она возникала,
# когда триаж лежал В ОДНОМ system-блоке с персонажем, а не когда стоял
# отдельным сообщением вплотную к точке генерации.
#
# THINK_MARKER живёт здесь (не в bot/ai_flow.py, который его раньше
# определял) — это часть протокола между роутером и вызывающим кодом,
# уместнее рядом с текстом промпта, который его порождает. Латиница
# принципиальна (не "ДУМАТЬ"): llm/service.py прогоняет ЛЮБОЙ ответ модели
# через SpeechTherapist.process (кириллическое р→г, llm/speech_therapy.py)
# ДО возврата вызывающему — кириллический маркер приходил бы уже испорченным
# и не совпадал бы со сравнением в коде (живой баг 2026-07-24, см. git-историю).
THINK_MARKER = "[[NEEDS_THINKING]]"
ROUTE_OK = "OK"

